def apply(chs):
    for c in chs:
        e=E.get(c["no"]) or {}
        if e.get("speech"): c["speech"]=e["speech"]
        if e.get("xmaps"): c["xmaps"]=list(e["xmaps"])
        if e.get("anims"): c["anims"]=list(e["anims"])
        if e.get("hard"):
            c.setdefault("hard", [])
            # avoid exact duplicate questions
            have={h[0] for h in c["hard"]}
            for q,a in e["hard"]:
                if q not in have:
                    c["hard"].append((q,a))
        if e.get("conf"):
            c.setdefault("conf", [])
            c["conf"]=list(c["conf"])+list(e["conf"])
